def kana_to_romaji(text):
    if not text or text == '-':
        return text
    # Very simple transliterator
    result = ""
    i = 0
    while i < len(text):
        if text[i] in [' ', ',', '.', '、', '。', '・', '-']:
            result += text[i]
            i += 1
            continue
            
        # check sokuon (small tsu)
        if text[i] == 'ッ' or text[i] == 'っ':
            if i + 1 < len(text):
                # We won't fully resolve the consonant here, just generic double
                result += "'" 
            i += 1
            continue

        # Check 2 chars (yoon)
        if i + 1 < len(text) and text[i:i+2] in kana_to_romaji_map:
            result += kana_to_romaji_map[text[i:i+2]]
            i += 2
        elif text[i] in kana_to_romaji_map:
            result += kana_to_romaji_map[text[i]]
            i += 1
        else:
            result += text[i]
            i += 1
    # fix generic double consonant
    result = re.sub(r"'([a-z])", r"\1\1", result)
    return result

def add_romaji_to_reading(readings_str):
    if not readings_str or readings_str == '-': return readings_str
    parts = [p.strip() for p in readings_str.split(',')]
    out = []
    for p in parts:
        # separate standard kana and okurigana if there's a dot
        if '.' in p:
            base, okuri = p.split('.', 1)
            romaji_b = kana_to_romaji(base)
            romaji_o = kana_to_romaji(okuri)
            out.append(f"{p} ({romaji_b}.{romaji_o})")
        else:
            romaji = kana_to_romaji(p)
            out.append(f"{p} ({romaji})")
    return ", ".join(out)

html_path = '/Users/yangcoi/Documents/jdp1.html'
with open(html_path, 'r', encoding='utf-8') as f:
    content = f.read()

# Replace on: '...', kun: '...'
def replacer(match):
    full = match.group(0)
    on_match = re.search(r"on:\s*'([^']+)'", full)
    kun_match = re.search(r"kun:\s*'([^']+)'", full)
    
    if on_match:
        on_val = on_match.group(1)
        # Avoid double transliteration
        if '(' not in on_val:
            new_on = add_romaji_to_reading(on_val)
            full = full.replace(f"on: '{on_val}'", f"on: '{new_on}'")
            
    if kun_match:
        kun_val = kun_match.group(1)
        if '(' not in kun_val:
            new_kun = add_romaji_to_reading(kun_val)
            full = full.replace(f"kun: '{kun_val}'", f"kun: '{new_kun}'")
            
    return full

pattern = re.compile(r"\{\s*kanji:\s*'[^']+',.*?\}")
new_content = pattern.sub(replacer, content)

with open(html_path, 'w', encoding='utf-8') as f:
    f.write(new_content)

